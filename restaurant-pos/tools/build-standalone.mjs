// Builds restaurant-pos-standalone.html: the restaurant app as ONE file that opens directly in the
// browser (double-click), like the hotel reference file. Everything is inside the file — React,
// QZ Tray library, styles, the tested money/receipt code and the app — so it also works offline.
//   npm i --no-save @babel/standalone   (once, only needed to rebuild)
//   node tools/build-standalone.mjs
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
let Babel;
try { Babel = require("@babel/standalone"); } catch { Babel = require(process.env.BABEL_STANDALONE || "@babel/standalone"); }

// Shared, unit-tested modules become plain global functions.
const plain = (file) => read(file)
  .replace(/^import [^;]+;$/gm, "")
  .replace(/^export (async function|function|const|let) /gm, "$1 ");
const shared = plain("shared/money.js") + "\n" + plain("shared/receipt.js");
if (/^\s*(import|export)\b/m.test(shared)) throw new Error("unexpected import/export in shared code");

const app = Babel.transform(read("standalone/app.jsx"), { presets: [["react", { runtime: "classic" }]], comments: true, compact: false, retainLines: false }).code;
const safe = (js) => js.replace(/<\/script/gi, "<\\/script");
const favicon = "data:image/svg+xml," + encodeURIComponent(read("public/favicon.svg").trim());

const css = read("public/css/app.css") + "\n" + read("public/css/receipt.css") + `
/* single-file edition */
main { padding: 0; max-width: none; }
@media (max-width: 980px) { .service-grid { grid-template-columns: 1fr !important; } }
.menu-tile { cursor: pointer; }
`;

const html = `<!DOCTYPE html>
<!--
  Hailu Beyene Minda Restaurant — Restaurant POS (single-file edition)
  Open this file directly in Chrome or Edge. No server and no internet needed.
  Data is stored in this browser on this computer (IndexedDB): make a backup daily (Atelier → Backup).
  Printing: install QZ Tray (https://qz.io/download) on this computer.
  Generated by tools/build-standalone.mjs from standalone/app.jsx and shared/*.js — edit those, then rebuild.
-->
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>Hailu Beyene Minda Restaurant</title>
  <link rel="icon" href="${favicon}">
  <meta name="theme-color" content="#3d2817">
  <link href="https://fonts.googleapis.com/css2?family=Playfair+Display:wght@400;700;900&family=DM+Sans:wght@400;500;700&family=Noto+Sans+Ethiopic:wght@400;500;700&family=Space+Mono:wght@400;700&display=swap" rel="stylesheet">
  <style>
${css}
  </style>
</head>
<body>
  <div id="root"><div style="display:flex;align-items:center;justify-content:center;height:100vh;font-family:Georgia,serif;color:#c8553d;font-size:24px">Hailu Beyene Minda Restaurant — loading…</div></div>
  <script>
/* React 18.3.1 (MIT) */
${safe(read("public/vendor/react.production.min.js"))}
  </script>
  <script>
/* ReactDOM 18.3.1 (MIT) */
${safe(read("public/vendor/react-dom.production.min.js"))}
  </script>
  <script>
/* QZ Tray Local Network Access helper, qz-lna 0.1.2 (MIT, QZ Industries, LLC) */
${safe(read("public/vendor/qz-lna.bundle.min.js"))}
  </script>
  <script>
/* QZ Tray client library, qz-tray.js 2.3.0 (LGPL-2.1-only, QZ Industries, LLC) */
${safe(read("public/vendor/qz-tray.js"))}
  </script>
  <script>
"use strict";
/* ===== Money, VAT and receipt layout (shared/money.js + shared/receipt.js, covered by npm test) ===== */
${safe(shared)}
  </script>
  <script>
"use strict";
/* ===== Restaurant app (compiled from standalone/app.jsx) ===== */
${safe(app)}
  </script>
</body>
</html>
`;
const out = path.join(ROOT, "restaurant-pos-standalone.html");
fs.writeFileSync(out, html);
console.log(`Wrote ${path.relative(ROOT, out)} (${(html.length / 1024).toFixed(0)} KB)`);
